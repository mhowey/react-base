#!/usr/bin/env bash
# One-time bootstrap of a fresh Ubuntu 22.04/24.04 or Debian 12 VPS (e.g. CloudCone).
# Installs Node.js 22, Caddy (automatic HTTPS), clones + builds the app, and runs it under systemd.
# Safe to re-run: every step is idempotent and an existing .env is never overwritten.
#
# Usage (as root):
#   DOMAIN=news.example.com ADMIN_EMAILS=you@example.com bash setup-server.sh
#
# Optional variables:
#   REPO           git URL                       (default: https://github.com/mhowey/react-base.git)
#   BRANCH         branch to deploy              (default: main)
#   PORT           internal app port             (default: 3000)
#   SSH_PORT       your SSH port, kept open      (default: 22)
#   SKIP_FIREWALL  set to 1 to leave ufw alone
set -euo pipefail

DOMAIN="${DOMAIN:?Set DOMAIN, e.g. DOMAIN=news.example.com}"
ADMIN_EMAILS="${ADMIN_EMAILS:-}"
REPO="${REPO:-https://github.com/mhowey/react-base.git}"
BRANCH="${BRANCH:-main}"
PORT="${PORT:-3000}"
SSH_PORT="${SSH_PORT:-22}"
APP_NAME=react-base
APP_USER=reactbase
APP_DIR=/srv/$APP_NAME
DATA_DIR=/var/lib/$APP_NAME
BACKUP_DIR=/var/backups/$APP_NAME

log() { printf '\n\033[1;34m==> %s\033[0m\n' "$*"; }
[ "$(id -u)" -eq 0 ] || { echo "Run as root (sudo -i)"; exit 1; }
command -v apt-get >/dev/null || { echo "This script supports Debian/Ubuntu only"; exit 1; }
export DEBIAN_FRONTEND=noninteractive

log "Installing base packages"
apt-get update -y
apt-get install -y curl git ca-certificates gnupg openssl build-essential python3 sqlite3 ufw \
  debian-keyring debian-archive-keyring apt-transport-https

log "Ensuring swap (Vite builds need ~1 GB RAM)"
if [ "$(swapon --noheadings | wc -l)" -eq 0 ] && [ "$(awk '/MemTotal/ {print $2}' /proc/meminfo)" -lt 2000000 ]; then
  fallocate -l 2G /swapfile || dd if=/dev/zero of=/swapfile bs=1M count=2048
  chmod 600 /swapfile && mkswap /swapfile && swapon /swapfile
  grep -q '^/swapfile' /etc/fstab || echo '/swapfile none swap sw 0 0' >> /etc/fstab
fi

log "Installing Node.js 22"
if ! node -v 2>/dev/null | grep -Eq '^v(2[2-9]|[3-9][0-9])\.'; then
  curl -fsSL https://deb.nodesource.com/setup_22.x | bash -
  apt-get install -y nodejs
fi
node -v

log "Installing Caddy"
if ! command -v caddy >/dev/null; then
  curl -1sLf 'https://dl.cloudsmith.io/public/caddy/stable/gpg.key' | gpg --dearmor --yes -o /usr/share/keyrings/caddy-stable-archive-keyring.gpg
  curl -1sLf 'https://dl.cloudsmith.io/public/caddy/stable/debian.deb.txt' > /etc/apt/sources.list.d/caddy-stable.list
  apt-get update -y
  apt-get install -y caddy
fi

log "Creating service user and directories"
id "$APP_USER" >/dev/null 2>&1 || useradd --system --create-home --home-dir "/home/$APP_USER" --shell /usr/sbin/nologin "$APP_USER"
install -d -o "$APP_USER" -g "$APP_USER" -m 750 "$DATA_DIR"
install -d -o root -g root -m 700 "$BACKUP_DIR"

log "Fetching code ($REPO @ $BRANCH)"
if [ ! -d "$APP_DIR/.git" ]; then
  git clone --branch "$BRANCH" "$REPO" "$APP_DIR"
fi
chown -R "$APP_USER:$APP_USER" "$APP_DIR"

log "Writing $APP_DIR/.env (only if missing)"
if [ ! -f "$APP_DIR/.env" ]; then
  cat > "$APP_DIR/.env" <<EOF
# Generated by deploy/setup-server.sh on $(date -u +%F). Edit, then: systemctl restart $APP_NAME
NODE_ENV=production
PORT=$PORT
HOST=127.0.0.1
APP_URL=https://$DOMAIN
DATABASE_PATH=$DATA_DIR/app.db
JWT_SECRET=$(openssl rand -hex 32)
COOKIE_SECRET=$(openssl rand -hex 32)
SESSION_TTL_DAYS=7
# Comma separated. Admin rights for these emails. If empty, the FIRST person to sign in becomes admin.
ADMIN_EMAILS=$ADMIN_EMAILS
ENABLE_DEV_LOGIN=false

# OAuth (callback: https://$DOMAIN/api/auth/<google|facebook|github>/callback)
GOOGLE_CLIENT_ID=
GOOGLE_CLIENT_SECRET=
FACEBOOK_CLIENT_ID=
FACEBOOK_CLIENT_SECRET=
GITHUB_CLIENT_ID=
GITHUB_CLIENT_SECRET=
EOF
fi
chown "$APP_USER:$APP_USER" "$APP_DIR/.env"
chmod 600 "$APP_DIR/.env"

log "Installing dependencies and building"
sudo -u "$APP_USER" -H bash -c "cd '$APP_DIR' && npm ci --no-audit --no-fund && npm run build"

log "Installing systemd service"
sed -e "s|__APP_USER__|$APP_USER|g" -e "s|__APP_DIR__|$APP_DIR|g" -e "s|__DATA_DIR__|$DATA_DIR|g" \
  "$APP_DIR/deploy/react-base.service" > "/etc/systemd/system/$APP_NAME.service"
systemctl daemon-reload
systemctl enable "$APP_NAME" >/dev/null
systemctl restart "$APP_NAME"

log "Configuring Caddy for $DOMAIN"
sed -e "s|__DOMAIN__|$DOMAIN|g" -e "s|__PORT__|$PORT|g" "$APP_DIR/deploy/Caddyfile" > /etc/caddy/Caddyfile
caddy validate --config /etc/caddy/Caddyfile --adapter caddyfile >/dev/null
systemctl enable caddy >/dev/null
systemctl reload caddy || systemctl restart caddy

if [ "${SKIP_FIREWALL:-0}" != "1" ]; then
  log "Configuring firewall (SSH $SSH_PORT, HTTP, HTTPS)"
  ufw allow "$SSH_PORT/tcp" >/dev/null
  ufw allow 80/tcp >/dev/null
  ufw allow 443/tcp >/dev/null
  ufw --force enable >/dev/null
  ufw status
fi

log "Scheduling nightly database backups (03:17)"
install -m 755 "$APP_DIR/deploy/backup.sh" /usr/local/bin/$APP_NAME-backup
echo "17 3 * * * root /usr/local/bin/$APP_NAME-backup >> /var/log/$APP_NAME-backup.log 2>&1" > /etc/cron.d/$APP_NAME-backup
install -m 755 "$APP_DIR/deploy/deploy.sh" /usr/local/bin/$APP_NAME-deploy

log "Health check"
for _ in $(seq 1 30); do
  if curl -fsS "http://127.0.0.1:$PORT/api/health" >/dev/null; then
    echo "App is up on 127.0.0.1:$PORT"
    break
  fi
  sleep 1
done
curl -fsS "http://127.0.0.1:$PORT/api/health" >/dev/null || { journalctl -u "$APP_NAME" -n 50 --no-pager; exit 1; }

cat <<EOF

Done. Next steps:
  1. Make sure DNS for $DOMAIN points at this server's IP (A record, plus AAAA if you use IPv6).
     Caddy fetches the HTTPS certificate automatically once DNS resolves.
  2. Visit https://$DOMAIN
  3. Add OAuth credentials to $APP_DIR/.env, then: systemctl restart $APP_NAME
  4. Deploy updates later with:  $APP_NAME-deploy
  Logs: journalctl -u $APP_NAME -f     Caddy logs: journalctl -u caddy -f
EOF
